// tools/build.mjs in a scratch project: a build its checks reject leaves no bundle in package/, so
// tools/install.sh and tools/release.py (which require the bundle) refuse to ship it; a build that
// passes writes the bundle whole. The scratch project has the real tools and tsconfigs and a
// one-file src/.

import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "../..");
const BUNDLE = "package/contents/code/plastile.mjs";

function project(main: string, previous = true): string {
  const dir = mkdtempSync(join(tmpdir(), "plastile-build-"));
  mkdirSync(join(dir, "tools"));
  for (const f of ["build.mjs", "bundle-options.ts", "itercheck.ts", "qv4check.ts"]) copyFileSync(join(ROOT, "tools", f), join(dir, "tools", f));
  for (const f of ["tsconfig.json", "tsconfig.runtime.json"]) copyFileSync(join(ROOT, f), join(dir, f));
  writeFileSync(join(dir, "package.json"), JSON.stringify({ type: "module" }));
  symlinkSync(join(ROOT, "node_modules"), join(dir, "node_modules"));
  mkdirSync(join(dir, "src/runtime"), { recursive: true });
  writeFileSync(join(dir, "src/runtime/main.ts"), main);
  if (!previous) return dir; // a fresh checkout: package/contents/code/ is not tracked
  mkdirSync(join(dir, "package/contents/code"), { recursive: true });
  writeFileSync(join(dir, BUNDLE), "// the previous build\n");
  return dir;
}

function run(dir: string) {
  return spawnSync(process.execPath, ["tools/build.mjs"], { cwd: dir, encoding: "utf8", timeout: 60000 });
}

test("a bundle the QV4 check rejects is not left in package/ (nor the previous one)", () => {
  const dir = project("export function early(): number { return LATE; }\nexport const LATE = 1;\n");
  try {
    const r = run(dir);
    assert.equal(r.status, 1, r.stderr);
    assert.match(r.stderr, /"LATE" is used before its declaration/);
    assert.ok(!existsSync(join(dir, BUNDLE)), "no bundle for install.sh or release.py to pick up");
    assert.deepEqual(readdirSync(join(dir, "package/contents/code")), []);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("an iteration hazard in src/ removes the previous, now stale, bundle", () => {
  const dir = project("const m = new Map<string, number>();\nexport function walk(): void { for (const e of m) void e; }\n");
  try {
    const r = run(dir);
    assert.equal(r.status, 1, r.stderr);
    assert.ok(!existsSync(join(dir, BUNDLE)));
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("a build that passes writes the bundle with its header and nothing else", () => {
  const dir = project("export const LATE = 1;\nexport function early(): number { return LATE; }\n");
  try {
    const r = run(dir);
    assert.equal(r.status, 0, r.stderr);
    const text = readFileSync(join(dir, BUNDLE), "utf8");
    assert.match(text, /^\/\/ Generated by tools\/build\.mjs from src\/ — do not edit\.\n/);
    assert.match(text, /function early\(\)/);
    assert.deepEqual(readdirSync(join(dir, "package/contents/code")), ["plastile.mjs"]);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("a first build in a fresh checkout creates package/contents/code/", () => {
  const dir = project("export const LATE = 1;\n", false);
  try {
    const r = run(dir);
    assert.equal(r.status, 0, r.stderr);
    assert.deepEqual(readdirSync(join(dir, "package/contents/code")), ["plastile.mjs"]);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
