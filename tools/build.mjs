// Bundle the TypeScript runtime into the KWin package (options: tools/bundle-options.ts).
// Two checks fail the build:
//  - src/ walks a Map, a Set or one of their iterators with for...of (tools/itercheck.ts, type-aware):
//    QV4 skips an entry when the loop body deletes one (docs/validation/PERFORMANCE.md §7.1);
//  - the bundle references a variable above its declaration (tools/qv4check.ts; KWin logs
//    qt.qml.usedbeforedeclared for it).
// The bundle is built in memory and written only when both pass. A failed build removes the
// previous bundle, so tools/install.sh and tools/release.py, which require it, refuse to ship a
// bundle the build rejected or one that no longer matches src/.
import { build } from "esbuild";
import { mkdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { BUNDLE_OPTIONS, BUNDLE_OUT } from "./bundle-options.ts";
import { checkProject, formatHazard, RULE } from "./itercheck.ts";
import { usedBeforeDeclaration } from "./qv4check.ts";

const out = BUNDLE_OUT;

function fail(lines) {
  for (const l of lines) console.error(l);
  rmSync(out, { force: true });
  console.error(`removed ${out}: run npm run build again after fixing the above`);
  process.exit(1);
}

const hazards = checkProject(process.cwd());
if (hazards.length > 0) fail([...hazards.map(formatHazard), RULE]);

let result;
try {
  result = await build({ ...BUNDLE_OPTIONS, outfile: out, write: false, metafile: true });
} catch (_e) {
  fail([]); // esbuild has printed its errors
}
const code = result.outputFiles[0].text;
const bytes = Object.values(result.metafile.outputs)[0].bytes;
const early = usedBeforeDeclaration(code);
if (early.length > 0) {
  // Lines as in the written file, which has a one-line header.
  fail([...early.map((e) => `${out}:${e.ref.line + 1}: "${e.name}" is used before its declaration at line ${e.decl.line + 1} (QV4 warns at load)`),
    "declare these before the functions that use them"]);
}
// Mark the file as generated; write it whole, then rename, so no reader sees a partial bundle.
mkdirSync(dirname(out), { recursive: true }); // package/contents/code/ is not tracked
writeFileSync(`${out}.tmp`, "// Generated by tools/build.mjs from src/ — do not edit.\n" + code);
renameSync(`${out}.tmp`, out);
console.log(`built ${out} (${bytes} bytes)`);
