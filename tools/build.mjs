// Bundle the TypeScript runtime into the KWin package.
// Output: package/contents/code/plastile.mjs, an ECMAScript module imported by the
// declarative root as `import "../code/plastile.mjs" as Bundle` (no export getters,
// so QV4 emits no used-before-declared warnings at load).
// Target ES2016 lowers syntax KWin's QV4 (Qt 6.12) rejects: class fields, object
// spread/rest, async, logical assignment, optional catch binding (M0 probe).
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

const out = "package/contents/code/plastile.mjs";
const result = await build({
  entryPoints: ["src/runtime/main.ts"],
  bundle: true,
  format: "esm",
  target: "es2016",
  platform: "neutral",
  outfile: out,
  legalComments: "none",
  charset: "utf8",
  minify: false,
  metafile: true,
  logLevel: "warning",
});
// Mark the file as generated.
const code = readFileSync(out, "utf8");
writeFileSync(out, "// Generated by tools/build.mjs from src/ — do not edit.\n" + code);
const bytes = Object.values(result.metafile.outputs)[0].bytes;
console.log(`built ${out} (${bytes} bytes)`);
