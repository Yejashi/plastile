#!/usr/bin/env python3
"""Interleaved A/B/n of Plastile bundles built from different commits (G2 report §15 follow-up).

Only the bundle changes between variants. The measurement root (probes/perf/main.qml), the
QML package files it imports (package/contents/ui), the harness, the fixture, KWin and the
workload are this tree's, for every variant. Each variant's bundle is esbuild of that commit's
src/ with this tree's BUNDLE_OPTIONS (tools/bundle-options.ts), written into a private tree
under the output directory; nothing in this checkout is rebuilt.

Workload per unit (b60e618's probes/perf/run.py P03, the workload of the §15 A/B): one nested
KWin, n fixtures on one virtual output 1920 x ((n - 1) * 186 + 32), master/stack, no inactive
desktops; then 300 ratio (grow/shrink alternating), 300 swap.next, 300 focus.next, in that order,
15-30 ms seeded pauses (seed 1, as run.py), settled between workloads. Instrumented, as in the
A/B: the bundle's own dispatch -> return span and solve/apply spans, plus the root's outer span.

Units run one at a time, in rounds; each round runs every variant once in a seeded shuffled
order (interleaved, so drift spreads over all variants). Every sample is kept.

Variant syntax: REV (a commit-ish) or `worktree` (this checkout's src/ as it is now; recorded
with its dirty state, never publishable), followed by options joined with `+`:
  nostate     the root without the persistence store (no `state` passed to createRuntime, no
              Persistence.qml item)
  pick=REV2   apply REV2's own src/ change on top (patch -p1), e.g. a fix tested in an older tree

Nested KWin virtual backend only; nothing here is physical.

Usage: python3 probes/perf/ab_bundles.py --variants b60e618,HEAD [--rounds 4] [--n 32] [--samples 300]
           [--seed 20261019] [--out DIR] [--gc-log]
       python3 probes/perf/ab_bundles.py --summarize DIR [--reference VARIANT]
"""
from __future__ import annotations

import argparse
import json
import random
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tests/integration"))
sys.path.insert(0, str(HERE))
from harness import PLUGIN, Session  # noqa: E402
from workloads import load_quiet, measure_env  # noqa: E402
import perfcommon as common  # noqa: E402

PERF = re.compile(r"plastile perf (\{.*\})$")
OUTER = re.compile(r"plastile-measure outer (\[.*\])$")
WORKLOADS = ("ratio", "swap", "focus")
BUILD = r"""
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { BUNDLE_OPTIONS } from "./tools/bundle-options.ts";
const [tree, out] = process.argv.slice(1);
await build({ ...BUNDLE_OPTIONS, absWorkingDir: tree, outfile: out });
writeFileSync(out, "// Generated by probes/perf/ab_bundles.py from src/ - do not edit.\n" + readFileSync(out, "utf8"));
"""


def git(*a: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *a], capture_output=True, text=True, check=True).stdout.strip()


def prepare(spec: str, trees: Path) -> dict:
    """Build one variant's private tree; returns its provenance."""
    rev, *opts = spec.split("+")
    picks = [o.split("=", 1)[1] for o in opts if o.startswith("pick=")]
    opt = "nostate" if "nostate" in opts else ""
    unknown = [o for o in opts if o != "nostate" and not o.startswith("pick=")]
    if unknown:
        raise SystemExit(f"unknown variant option {unknown!r}")
    if rev == "worktree":
        sha, dirty = git("rev-parse", "HEAD"), bool(git("status", "--porcelain", "--", "src"))
    else:
        sha, dirty = git("rev-parse", rev + "^{commit}"), False
    name = (sha[:12] if rev != "worktree" else "worktree") + "".join("-" + o.replace("=", "-") for o in opts)
    tree = (trees / name).resolve()
    if tree.exists():
        shutil.rmtree(tree)
    tree.mkdir(parents=True)
    if rev == "worktree":
        shutil.copytree(ROOT / "src", tree / "src")
    else:
        arc = subprocess.run(["git", "-C", str(ROOT), "archive", sha, "src"], capture_output=True, check=True).stdout
        subprocess.run(["tar", "-x", "-C", str(tree)], input=arc, check=True)
    applied = []
    for pk in picks:
        # Apply one commit's own src/ change on top of the variant's src/ (a fix tested in an older tree).
        full = git("rev-parse", pk + "^{commit}")
        diff = subprocess.run(["git", "-C", str(ROOT), "diff", full + "^", full, "--", "src"],
                              capture_output=True, check=True).stdout
        subprocess.run(["patch", "-p1", "-s", "-d", str(tree)], input=diff, check=True)
        applied.append(full)
    (tree / "node_modules").symlink_to(ROOT / "node_modules")
    ui = tree / "package/contents/ui"
    shutil.copytree(ROOT / "package/contents/ui", ui)
    (tree / "package/contents/code").mkdir(parents=True)
    bundle = tree / "package/contents/code/plastile.mjs"
    subprocess.run(["node", "--input-type=module", "-e", BUILD, str(tree), str(bundle)], cwd=ROOT, check=True)
    (tree / "probes/perf").mkdir(parents=True)
    qml = (HERE / "main.qml").read_text()
    if opt == "nostate":
        qml = qml.replace("    Production.Persistence { id: persistence }\n", "")
        qml = qml.replace("            state: persistence,\n", "")
        assert "persistence" not in qml.split("Component.onCompleted")[1].split("Component.onDestruction")[0], "nostate edit"
    (tree / "probes/perf/main.qml").write_text(qml)
    return {"spec": spec, "name": name, "commit": sha, "picked": applied, "srcDirty": dirty, "bundleBytes": bundle.stat().st_size,
            "qml": str((tree / "probes/perf/main.qml").relative_to(ROOT)) if tree.is_relative_to(ROOT) else None,
            "tree": tree}


def unit(var: dict, n: int, samples: int, seed: int, out: Path, gc_log: bool) -> dict:
    env = measure_env()
    if gc_log:
        env["QT_LOGGING_RULES"] = "js=true;qml=true;kwin_scripting=true;qt.qml.gc.*=true"
    others = subprocess.run(["pgrep", "-c", "-f", "kwin_wayland --virtual"], capture_output=True, text=True).stdout.strip()
    rec = {"variant": var["spec"], "name": var["name"], "commit": var["commit"], "machineStart": common.machine_state(),
           "otherNestedKwinAtStart": int(others or 0)}
    rng = random.Random(seed)
    t_unit = time.monotonic()
    with Session(out / "session", width=1920, height=(n - 1) * 186 + 32, extra_env=env,
                 qml=var["tree"] / "probes/perf/main.qml", config={"diagnostics": "info"}) as s:
        for i in range(1, n + 1):
            s.spawn(i, wait=False)
        s.wait_for(lambda: len(s.frames_list()) == n, 30, f"{n} windows")
        load_quiet(s)
        c = s.settle(timeout=20)
        rec["overflowAtStart"] = c["counters"].get("overflow")
        s.act("plastile-fixture 1", "workspace.activeWindow = w")
        s.settle()
        off = s.kw.mark()
        sends = []
        for wl in WORKLOADS:
            for k in range(samples):
                cmd = {"ratio": "resize.grow" if k % 2 == 0 else "resize.shrink", "swap": "swap.next", "focus": "focus.next"}[wl]
                sends.append((wl, s.cmd(cmd)))
                time.sleep(rng.uniform(0.015, 0.03))
            s.settle()
        perf = [json.loads(PERF.search(ln).group(1)) for ln in s.log_lines(r"plastile perf ", off)]
        off2 = s.kw.mark()
        s.kw.invoke_shortcut("plastile-measure-dump")
        s.kw.wait_log(r"plastile-measure outer-end ", 10, off2)
        outer = []
        for ln in s.log_lines(r"plastile-measure outer \[", off2):
            outer += json.loads(OUTER.search(ln).group(1))
        outer = [o for o in outer if not o[0].startswith("plastile.inspect.")]
        end = s.counters()
        rec["final"] = {"counters": end["counters"], "outstanding": end["outstanding"]}
        rec["badLines"] = s.log_lines(r"plastile (error|warn)|TypeError|ReferenceError")[:10]
        if gc_log:
            lines = s.log_lines(r"qt\.qml\.gc|plastile perf ", off)
            (out / "gc.log").write_text("\n".join(lines) + "\n")
        s.kw.unload(PLUGIN)
        s.loaded = False
        time.sleep(0.3)
        rec["unloaded"] = not s.kw.is_loaded(PLUGIN)
    rec["seconds"] = round(time.monotonic() - t_unit, 1)
    rows = {wl: [] for wl in WORKLOADS}
    ok = len(perf) == len(sends) == len(outer)
    for i, (wl, t_send) in enumerate(sends):
        p = perf[i] if i < len(perf) else None
        o = outer[i] if i < len(outer) else None
        t = (p or {}).get("timing") or {}
        rows[wl].append({"inner": p["dispatchToReturnNs"] if p else None, "outer": o[2] if o else None,
                         "solve": t.get("solveNs"), "apply": t.get("applyNs"), "writes": t.get("writes"),
                         "status": p["status"] if p else None, "sendToEntry": (p["entryNs"] - t_send) if p else None})
    rec["countsMatch"] = ok
    rec["samples"] = rows
    rec["machineEnd"] = common.machine_state()
    return rec


def q(xs: list[float], p: float) -> float | None:
    import math
    s = sorted(x for x in xs if x is not None)
    return s[max(1, math.ceil(p * len(s))) - 1] if s else None


def summarize(d: Path, reference: str | None, b: int = 4000) -> dict:
    units = [json.loads(p.read_text()) for p in sorted(d.glob("u*/unit.json"))]
    by: dict[str, list[dict]] = {}
    for u in units:
        by.setdefault(u["variant"], []).append(u)
    meta = json.loads((d / "campaign.json").read_text())
    order = [v["spec"] for v in meta["variants"]]
    ref = reference or order[0]
    rng = random.Random(1)
    out = {"reference": ref, "variants": {}}
    for v in order:
        us = by.get(v, [])
        cell = {"units": len(us), "commit": us[0]["commit"] if us else None, "bundleBytes": next((x["bundleBytes"] for x in meta["variants"] if x["spec"] == v), None)}
        for wl in WORKLOADS:
            for span in ("inner", "outer", "solve", "apply"):
                runs = [[r[span] / 1e6 for r in u["samples"][wl] if r[span] is not None] for u in us]
                runs = [r for r in runs if r]
                if not runs:
                    continue
                pooled = [x for r in runs for x in r]
                key = f"{wl}.{span}"
                c = {"n": len(pooled), "p50": q(pooled, 0.5), "p95": q(pooled, 0.95), "max": max(pooled),
                     "runP50": [round(q(r, 0.5), 4) for r in runs]}
                if v != ref and by.get(ref):
                    rr = [[r[span] / 1e6 for r in u["samples"][wl] if r[span] is not None] for u in by[ref]]
                    rr = [r for r in rr if r]
                    if rr:
                        diffs = []
                        for _ in range(b):
                            a = [x for r in (rng.choice(runs) for _ in runs) for x in r]
                            z = [x for r in (rng.choice(rr) for _ in rr) for x in r]
                            diffs.append(q(a, 0.5) - q(z, 0.5))
                        diffs.sort()
                        c["p50DiffVsRef"] = round(q(pooled, 0.5) - q([x for r in rr for x in r], 0.5), 4)
                        c["p50DiffCI95"] = [round(diffs[int(0.025 * b)], 4), round(diffs[int(0.975 * b) - 1], 4)]
                cell[key] = {k: (round(x, 4) if isinstance(x, float) else x) for k, x in c.items()}
        out["variants"][v] = cell
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--variants")
    ap.add_argument("--rounds", type=int, default=4)
    ap.add_argument("--n", type=int, default=32)
    ap.add_argument("--samples", type=int, default=300)
    ap.add_argument("--seed", type=int, default=20261019)
    ap.add_argument("--gc-log", action="store_true", help="QV4 GC log (perturbs timing; diagnostic only)")
    ap.add_argument("--out", type=Path)
    ap.add_argument("--summarize", type=Path)
    ap.add_argument("--reference")
    args = ap.parse_args()
    if args.summarize:
        s = summarize(args.summarize, args.reference)
        (args.summarize / "summary.json").write_text(json.dumps(s, indent=1))
        for v, c in s["variants"].items():
            r = c.get("ratio.inner", {})
            w = c.get("swap.inner", {})
            print(f"{v:24s} units={c['units']} ratio inner p50 {r.get('p50')} d={r.get('p50DiffVsRef')} {r.get('p50DiffCI95')}"
                  f" | swap {w.get('p50')} d={w.get('p50DiffVsRef')} {w.get('p50DiffCI95')}"
                  f" | ratio solve {c.get('ratio.solve', {}).get('p50')} apply {c.get('ratio.apply', {}).get('p50')}")
        return 0
    out = args.out or ROOT / "artifacts/perf/ab" / time.strftime("%Y%m%dT%H%M%S")
    out.mkdir(parents=True, exist_ok=True)
    specs = args.variants.split(",")
    variants = [prepare(sp, out / "trees") for sp in specs]
    meta = {"probe": "P03-bisect", **common.git_meta(), "versions": common.versions(),
            "layer": "nested KWin virtual backend (not physical); kglobalaccel D-Bus command API, not input",
            "n": args.n, "samples": args.samples, "rounds": args.rounds, "seed": args.seed, "gcLog": args.gc_log,
            "variants": [{k: v for k, v in x.items() if k != "tree"} for x in variants]}
    rng = random.Random(args.seed)
    plan = []
    for r in range(args.rounds):
        idx = list(range(len(variants)))
        rng.shuffle(idx)
        plan += [(r, i) for i in idx]
    meta["order"] = [f"r{r}:{variants[i]['spec']}" for r, i in plan]
    common.write_json(out / "campaign.json", meta)
    for k, (r, i) in enumerate(plan):
        v = variants[i]
        ud = out / f"u{k:03d}-r{r}-{v['name']}"
        ud.mkdir()
        t = time.monotonic()
        rec = unit(v, args.n, args.samples, 1, ud, args.gc_log)
        rec["round"] = r
        common.write_json(ud / "unit.json", rec)
        rp = sorted(x["inner"] for x in rec["samples"]["ratio"] if x["inner"] is not None)
        sp = sorted(x["inner"] for x in rec["samples"]["swap"] if x["inner"] is not None)
        print(f"[{k + 1}/{len(plan)}] r{r} {v['spec']}: ratio inner p50 {rp[len(rp) // 2] / 1e3:.0f} us, swap {sp[len(sp) // 2] / 1e3:.0f} us,"
              f" match={rec['countsMatch']} bad={len(rec['badLines'])} others={rec['otherNestedKwinAtStart']} {time.monotonic() - t:.0f}s",
              flush=True)
    s = summarize(out, None)
    (out / "summary.json").write_text(json.dumps(s, indent=1))
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
